"""
Generate include/test.h for the mm_matmul_mglib test:
  MATMUL: Z = X @ W        (z_mm)
  GEMM:   Z = X @ W + Y    (z_gemm)

The entries are small integers, so every product and sum is exact in fp16 and
the results must match bit by bit. The sizes are not multiples of the RedMulE
array (8 rows, 16 columns, 16-element X chunks), to exercise the leftovers.

Usage:
  python3 tests/magia/mesh/mm_matmul_mglib/gen_golden.py
"""

import os

import numpy as np

M, N, K = 12, 20, 24
SEED = 42

OUTPUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "include", "test.h")


def array(name, a):
    words = ", ".join(f"0x{v:04x}" for v in a.view(np.uint16).ravel())
    return f"uint16_t {name}[{a.size}] = {{{words}}};\n\n"


def main():
    rng = np.random.default_rng(SEED)
    x = rng.integers(-2, 3, (M, N)).astype(np.float16)
    w = rng.integers(-2, 3, (N, K)).astype(np.float16)
    y = rng.integers(-8, 9, (M, K)).astype(np.float16)
    xw = x.astype(np.float32) @ w.astype(np.float32)
    z_mm = xw.astype(np.float16)
    z_gemm = (xw + y.astype(np.float32)).astype(np.float16)

    with open(OUTPUT, "w") as f:
        f.write("// Copyright 2026 ETH Zurich, University of Bologna and Fondazione Chips-IT.\n"
                "// Licensed under the Apache License, Version 2.0, see LICENSE for details.\n"
                "// SPDX-License-Identifier: Apache-2.0\n"
                f"// Generated by gen_golden.py (M={M}, N={N}, K={K}, seed={SEED})\n"
                "//\n"
                f"// MATMUL: Z[{M}x{K}] = X[{M}x{N}] @ W[{N}x{K}]; GEMM: Z = X @ W + Y\n\n"
                "#ifndef _TEST_MM_MATMUL_INCLUDE_GUARD_\n"
                "#define _TEST_MM_MATMUL_INCLUDE_GUARD_\n\n"
                f"#define M_SIZE ({M})\n#define N_SIZE ({N})\n#define K_SIZE ({K})\n\n")
        for name, a in (("x_inp", x), ("w_inp", w), ("y_inp", y), ("z_mm", z_mm), ("z_gemm", z_gemm)):
            f.write(array(name, a))
        f.write("#endif\n")


if __name__ == "__main__":
    main()
