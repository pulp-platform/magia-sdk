"""
Generate include/test.h for the mm_matmul_mgc test: Z = X @ W, no bias.

The entries are small integers, so every product and partial sum is exact in
fp16 and the result must match bit by bit.

Usage:
  python3 tests/magia/mgc/mm_matmul_mgc/gen_golden.py
"""

import os

import numpy as np

M, N, K = 64, 256, 64
SEED = 42

OUTPUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "include", "test.h")


def array(name, a):
    words = ", ".join(f"0x{v:04x}" for v in a.view(np.uint16).ravel())
    return f"uint16_t {name}[{a.size}] = {{{words}}};\n\n"


def main():
    rng = np.random.default_rng(SEED)
    x = rng.integers(-2, 3, (M, N)).astype(np.float16)
    w = rng.integers(-2, 3, (N, K)).astype(np.float16)
    z = (x.astype(np.float32) @ w.astype(np.float32)).astype(np.float16)
    # result, stored by the test: filled with non-zero values (not .bss, and a
    # missing store cannot pass for a result)
    y = np.full((M, K), -1, np.float16)

    with open(OUTPUT, "w") as f:
        f.write("// Copyright 2026 ETH Zurich, University of Bologna and Fondazione Chips-IT.\n"
                "// Licensed under the Apache License, Version 2.0, see LICENSE for details.\n"
                "// SPDX-License-Identifier: Apache-2.0\n"
                f"// Generated by gen_golden.py (M={M}, N={N}, K={K}, seed={SEED})\n"
                "//\n"
                f"// MATMUL: Z[{M}x{K}] = X[{M}x{N}] @ W[{N}x{K}]\n\n"
                "#ifndef _TEST_MM_MATMUL_MGC_INCLUDE_GUARD_\n"
                "#define _TEST_MM_MATMUL_MGC_INCLUDE_GUARD_\n\n"
                f"#define M_SIZE ({M})\n#define N_SIZE ({N})\n#define K_SIZE ({K})\n\n")
        for name, a in (("x_inp", x), ("w_inp", w), ("y_out", y), ("z_out", z)):
            f.write(array(name, a))
        f.write("#endif\n")


if __name__ == "__main__":
    main()
