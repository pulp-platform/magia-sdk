"""
Generate include/test.h for unfused_attn:

  O[S x P] = softmax(Q[S x P] @ Kt[P x S] / sqrt(P)) @ V[S x P]

computed unfused: attn = Q @ Kt on RedMulE, row softmax on Spatz, O = attn @ V on RedMulE.
Q, Kt and V are those of mm_generator/flat_attn.py (same seed and ranges), so the inputs match
the flat_attn_* tests. The golden is a bit-true FP16 model of the RedMulE matmuls and of
the softmax_rows Spatz kernel.

Usage:
  python3 tests/magia/mgc/unfused_attn/gen_golden.py
"""

import argparse
import os
import sys

import numpy as np
import torch

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'mm_generator'))
from bittrue import matrix_multiply_with_bittrue_fma, write_fp16_array  # noqa: E402

parser = argparse.ArgumentParser("Unfused attention test")
parser.add_argument('--s_size', type=int, default=1024)  # SEQ_LENGTH
parser.add_argument('--p_size', type=int, default=64)    # PROJ_SIZE
parser.add_argument('--qk_range', type=float, default=2.0)
parser.add_argument('--seed', type=int, default=42)
args = parser.parse_args()

s_size, p_size, r = args.s_size, args.p_size, args.qk_range
LANES = 128  # VLEN 512 at e32 m8: one fp32 partial sum per lane

# same draws as flat_attn.py
torch.manual_seed(args.seed)
Q  = ((torch.rand(s_size, p_size) * 2 - 1) * r).to(torch.float16).numpy()
Kt = ((torch.rand(p_size, s_size) * 2 - 1) * r).to(torch.float16).numpy()
V  = torch.rand(s_size, p_size).to(torch.float16).numpy()


def f16(x):
    # every Spatz FP16 op: exact in float64, then one rounding
    return np.asarray(x, dtype=np.float64).astype(np.float16)


print("\nComputing bit-true unfused attention..")

# attn = Q @ Kt on RedMulE (MATMUL, accumulation from 0 in k order)
attn = matrix_multiply_with_bittrue_fma(Q, Kt, np.float16(0))

# softmax_rows: the scale s = 1/sqrt(P) is folded into the exp clamp and coefficient
s    = np.float16(1.0 / np.sqrt(np.float32(p_size)))
emin = np.float16(np.float32(-10.0) / np.float32(s))
coef = np.float16(np.float32(1477.0) * np.float32(s))
m    = attn.max(axis=1)
x    = np.maximum(f16(attn.astype(np.float64) - m[:, None]), emin)
x    = f16(f16(x.astype(np.float64) * coef).astype(np.float64) + 15360.0)
y    = np.trunc(x.astype(np.float64)).astype(np.uint16).view(np.float16)
# fp32 partial per lane over the row chunks, then the ordered (vfredusum) reduction
part = np.zeros((s_size, LANES), np.float32)
for c in range(0, s_size, LANES):
    part = (part + y[:, c:c + LANES].astype(np.float32)).astype(np.float32)
tot = np.zeros(s_size, np.float32)
for lane in range(LANES):
    tot = (tot + part[:, lane]).astype(np.float32)
rcp  = (np.float32(1.0) / tot).astype(np.float16)
attn = f16(y.astype(np.float64) * rcp[:, None])

# O = attn @ V on RedMulE
O = matrix_multiply_with_bittrue_fma(attn, V, np.float16(0))

ref = Q.astype(np.float64) @ Kt.astype(np.float64) / np.sqrt(p_size)
ref = np.exp(ref - ref.max(axis=1, keepdims=True))
ref = (ref / ref.sum(axis=1, keepdims=True)) @ V.astype(np.float64)
print("Max abs error w.r.t. float64 reference: ", np.abs(O.astype(np.float64) - ref).max())

inc_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'include')
os.makedirs(inc_path, exist_ok=True)
with open(os.path.join(inc_path, 'test.h'), 'w') as f:
    f.write('// Copyright 2026 ETH Zurich, University of Bologna and Fondazione Chips-IT.\n'
            '// Licensed under the Apache License, Version 2.0, see LICENSE for details.\n'
            '// SPDX-License-Identifier: Apache-2.0\n'
            '// Generated by gen_golden.py (S=%d, P=%d, qk_range=%g, seed=%d)\n'
            '//\n'
            '// Unfused attention: O[%dx%d] = softmax(Q[%dx%d] @ Kt[%dx%d] / sqrt(%d)) @ V[%dx%d]\n\n'
            % (s_size, p_size, r, args.seed, s_size, p_size, s_size, p_size, p_size, s_size,
               p_size, s_size, p_size))
    f.write('#ifndef _TEST_UNFUSED_ATTN_INCLUDE_GUARD_\n#define _TEST_UNFUSED_ATTN_INCLUDE_GUARD_\n\n')
    f.write('#define SEQ_LENGTH (%d)\n#define PROJ_SIZE  (%d)\n\n' % (s_size, p_size))
    write_fp16_array(f, 'q_inp [SEQ_LENGTH * PROJ_SIZE]', Q)
    write_fp16_array(f, 'k_inp [SEQ_LENGTH * PROJ_SIZE]', Kt)
    write_fp16_array(f, 'v_inp [SEQ_LENGTH * PROJ_SIZE]', V)
    f.write('uint16_t o_out [SEQ_LENGTH * PROJ_SIZE] = {0};\n\n')
    f.write('// attn [S x S] between the three steps: L2 scratch, not cleared by crt0\n')
    f.write('uint16_t attn_l2 [SEQ_LENGTH * SEQ_LENGTH] __attribute__((section(".shbss")));\n\n')
    write_fp16_array(f, 'o_gold[SEQ_LENGTH * PROJ_SIZE]', O)
    f.write('#endif //_TEST_UNFUSED_ATTN_INCLUDE_GUARD_\n')
