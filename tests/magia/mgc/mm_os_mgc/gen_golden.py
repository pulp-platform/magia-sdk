"""
Generate include/test.h for mm_os_mgc: Z[M x K] = X[M x N] @ W[N x K] + Y[M x K], fp16 data
in U(-0.5, 0.5). The golden is bit-true: one FP16 FMA per n, in n order, starting from Y, as
RedMulE accumulates over the timeslots. The L2 arrays go in .l2ext when they do not fit the
default L2 (12 MiB, run gvsoc with l2_size >= 0x10000000).

Usage:
  python3 tests/magia/mgc/mm_os_mgc/gen_golden.py --m 128 --n 512 --k 128
"""

import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'mesh', 'mm_generator'))
from bittrue import matrix_multiply_with_bittrue_fma  # noqa: E402

parser = argparse.ArgumentParser("Output-static GEMM test")
parser.add_argument('--m', type=int, default=128)  # M_SIZE
parser.add_argument('--n', type=int, default=512)  # N_SIZE (reduction)
parser.add_argument('--k', type=int, default=128)  # K_SIZE
parser.add_argument('--seed', type=int, default=42)
# place the L2 arrays in the .l2ext section (above the default gvsoc L2), by default when > 12 MiB
parser.add_argument('--l2ext', choices=['auto', 'yes', 'no'], default='auto')
parser.add_argument('--inc_dir', type=str, default=os.path.join(os.path.dirname(os.path.abspath(__file__)), 'include'))
args = parser.parse_args()
M, N, K = args.m, args.n, args.k


def write_fp16_array(f, decl, a):
    v = np.ascontiguousarray(a, dtype=np.float16).view(np.uint16).ravel()
    f.write('uint16_t %s __attribute__((aligned(64))) = {\n' % decl)
    for i in range(0, len(v), 16):
        f.write(', '.join('0x%04x' % x for x in v[i:i + 16].tolist()) + ',\n')
    f.write('};\n\n')


rng = np.random.default_rng(args.seed)
X = rng.uniform(-0.5, 0.5, (M, N)).astype(np.float16)
W = rng.uniform(-0.5, 0.5, (N, K)).astype(np.float16)
Y = rng.uniform(-0.5, 0.5, (M, K)).astype(np.float16)
Z = matrix_multiply_with_bittrue_fma(X, W, Y)

l2_bytes = 2 * (M * N + N * K + 2 * M * K)
l2ext = args.l2ext == 'yes' or (args.l2ext == 'auto' and l2_bytes > 12 * 2**20)
print("L2 arrays: %.1f MiB, %s" % (l2_bytes / 2**20, 'in .l2ext (needs l2_size >= 0x10000000)' if l2ext
                                  else 'in the default data region'))

os.makedirs(args.inc_dir, exist_ok=True)
with open(os.path.join(args.inc_dir, 'test.h'), 'w') as f:
    f.write('// Copyright 2026 ETH Zurich, University of Bologna and Fondazione Chips-IT.\n')
    f.write('// Licensed under the Apache License, Version 2.0, see LICENSE for details.\n')
    f.write('// SPDX-License-Identifier: Apache-2.0\n')
    f.write('// Generated by mm_os_mgc/gen_golden.py (M=%d, N=%d, K=%d, seed=%d)\n' % (M, N, K, args.seed))
    f.write('//\n')
    f.write('// GEMM with bias: Z[%dx%d] = X[%dx%d] @ W[%dx%d] + Y[%dx%d]\n' % (M, K, M, N, N, K, M, K))
    f.write('\n')
    f.write('#ifndef _TEST_MM_OS_INCLUDE_GUARD_\n')
    f.write('#define _TEST_MM_OS_INCLUDE_GUARD_\n')
    f.write('\n')
    f.write('#define M_SIZE (%d)\n' % M)
    f.write('#define N_SIZE (%d)\n' % N)
    f.write('#define K_SIZE (%d)\n' % K)
    f.write('\n')
    if l2ext:
        f.write('// %.1f MiB of L2 arrays: in .l2ext, above the default L2 (build and run gvsoc with\n' % (l2_bytes / 2**20))
        f.write('// l2_size >= 0x10000000)\n')
        f.write('#define L2EXT __attribute__((section(".l2ext")))\n')
    else:
        f.write('#define L2EXT\n')
    f.write('\n')
    write_fp16_array(f, 'x_inp[M_SIZE * N_SIZE] L2EXT', X)
    write_fp16_array(f, 'w_inp[N_SIZE * K_SIZE] L2EXT', W)
    write_fp16_array(f, 'y_inp[M_SIZE * K_SIZE] L2EXT', Y)
    write_fp16_array(f, 'z_out[M_SIZE * K_SIZE] L2EXT', Z)
    f.write('#endif //_TEST_MM_OS_INCLUDE_GUARD_\n')
